`timescale 1ns / 1ps

module datapath(
    input wire clk,
    input wire rst,
    input wire Reg2Loc_id, Unconditionbranch_id, Branch_id, Memread_id, MemtoReg_id, Memwrite_id, ALUSrc_id, Regwrite_id,
    input wire [3:0] ALUop_id,
    input logic hazardmux_id, idhold_id, pchold_id,
    input logic [1:0] fwdmuxa_id, fwdmuxb_id,

    // Instruction memory pipelined request/response interface
    output wire [63:0] imem_req_addr,
    output wire        imem_req_valid,
    input  wire        imem_req_ready,

    input  wire        imem_rsp_valid,
    output wire        imem_rsp_ready,
    input  wire [63:0] imem_rsp_addr,
    input  wire [31:0] imem_rsp_data,

    output wire        imem_flush,

    // Data memory request/ack interface
    output wire [63:0] dmem_addr,
    output wire [63:0] dmem_wdata,
    output wire        dmem_we,
    output wire        dmem_re,
    input  wire        dmem_ready,
    input  wire [63:0] dmem_rdata,

    output wire [4:0] Rn_id, Rm_id,
    output logic [31:0] instruction_id,
    output logic [4:0] Rd_ex, Rd_mem,
    output logic Memread_ex, Regwrite_ex, MemtoReg_mem,
    output logic [4:0] Rm_ex, Rn_ex, Rd_wb,
    output logic Regwrite_mem, Regwrite_wb,
    output logic [1:0] fwdmuxa_ex, fwdmuxb_ex
);

    // Global stall generated by an older data-memory operation in MEM.
    wire mem_wait;

    // Branch condition is evaluated in EX but the redirect decision is
    // registered into EX/MEM.  The registered MEM-stage redirect then drives
    // PC/flush controls.  This removes the wide CBZ reduction and forwarding
    // logic from the high-fanout PC/flush timing cone at the cost of one extra
    // branch-penalty cycle, while keeping the five architectural pipeline stages.
    logic Branch_ex, Unconditionbranch_ex;
    logic [63:0] branch_target_ex;
    logic        branch_taken_mem;
    logic [63:0] branch_target_mem;
    wire         branch_taken_ex_comb;

    /*==============
         IF stage
      ==============*/

    wire [63:0] pc_if, pc_next, pc_4_if;
    wire [31:0] instruction_if;

    wire imem_req_fire;
    wire imem_rsp_fire;
    wire front_stall;
    wire pc_hold_all;

    assign pc_4_if = pc_if + 64'd4;
    assign pc_next = branch_taken_mem ? branch_target_mem : pc_4_if;

    assign front_stall = pchold_id | idhold_id | mem_wait;

    assign imem_req_addr  = pc_if;
    assign imem_req_valid = !rst && !front_stall && !branch_taken_mem;
    assign imem_req_fire  = imem_req_valid && imem_req_ready;

    assign imem_rsp_ready = !rst && !front_stall && !branch_taken_mem;
    assign imem_rsp_fire  = imem_rsp_valid && imem_rsp_ready;

    assign imem_flush = branch_taken_mem;

    // A registered taken branch overrides the normal request-driven PC hold.
    assign pc_hold_all = !branch_taken_mem && !imem_req_fire;

    programcounter PC (
        .clk(clk),
        .rst(rst),
        .pc_next(pc_next),
        .pchold(pc_hold_all),
        .pc(pc_if)
    );

    assign instruction_if = imem_rsp_data;

    /*==============
         ID stage
      ==============*/

    logic [63:0] pc_id;
    wire [63:0] Readdata1_id, Readdata2_id;
    wire        Readdata2_zero_id;
    wire [63:0] SE_Dtaddr_id;
    wire [63:0] branch_offset_id;
    wire [63:0] branch_target_id;
    wire [5:0] shamt_id;
    wire [4:0] Rd_id;

    assign shamt_id = instruction_id[15:10];
    assign Rm_id    = Reg2Loc_id ? instruction_id[4:0] : instruction_id[20:16];
    assign Rn_id    = instruction_id[9:5];
    assign Rd_id    = instruction_id[4:0];

    assign branch_offset_id = SE_Dtaddr_id << 2;

    // Use the same logarithmic prefix topology as the ALU instead of relying on
    // a generic 64-bit '+' mapping for the branch-target path.
    prefix_addsub64 u_branch_target_add (
        .a   (pc_id),
        .b   (branch_offset_id),
        .sub (1'b0),
        .sum (branch_target_id)
    );

    signextension SE (
        .instruction(instruction_id),
        .SE_Dtaddr(SE_Dtaddr_id)
    );

    register REG (
        .clk(clk),
        .Rm(Rm_id),
        .Rn(Rn_id),
        .Rd(Rd_wb),
        .Regwrite(Regwrite_wb),
        .Regwritedata(Regwritedata_wb),
        .Regwrite_zero(Regwritedata_zero_wb),
        .Readdata1(Readdata1_id),
        .Readdata2(Readdata2_id),
        .Readdata2_zero(Readdata2_zero_id)
    );

    /*==============
         EX stage
      ==============*/

    logic [63:0] Readdata1_ex, Readdata2_ex, SE_Dtaddr_ex;
    logic        Readdata2_zero_ex;
    logic MemtoReg_ex, Memwrite_ex, ALUSrc_ex;
    logic [3:0] ALUop_ex;
    logic [5:0] shamt_ex;

    wire [63:0] result_ex;
    wire [63:0] Readdata1_ex_mux;
    wire [63:0] Readdata2_ex_mux;
    wire [63:0] Readdata2_ex_Src;
    wire branch_zero_ex;
    wire branch_zero_reg_ex;
    wire branch_zero_mem_ex;
    wire branch_zero_wb_ex;

    // fwdmuxa_ex/fwdmuxb_ex are registered ID/EX metadata.  No register-number
    // compare or forwarding-priority logic remains in front of the ALU.
    assign Readdata1_ex_mux =
        (fwdmuxa_ex == 2'b10) ? result_mem :
        (fwdmuxa_ex == 2'b01) ? Regwritedata_wb :
                                Readdata1_ex;

    assign Readdata2_ex_mux =
        (fwdmuxb_ex == 2'b10) ? result_mem :
        (fwdmuxb_ex == 2'b01) ? Regwritedata_wb :
                                Readdata2_ex;

    assign Readdata2_ex_Src = ALUSrc_ex ? SE_Dtaddr_ex : Readdata2_ex_mux;

    // Non-forwarded and WB-forwarded CBZ sources use registered one-bit zero
    // metadata.  A MEM-forwarded result still requires a reduction of the
    // already-registered result_mem bus; that reduction now terminates at the
    // single branch_taken_mem FF rather than driving PC/flush directly.
    assign branch_zero_reg_ex = Readdata2_zero_ex;
    assign branch_zero_mem_ex = ~|result_mem;
    assign branch_zero_wb_ex  = Regwritedata_zero_wb;

    assign branch_zero_ex =
        (fwdmuxb_ex == 2'b10) ? branch_zero_mem_ex :
        (fwdmuxb_ex == 2'b01) ? branch_zero_wb_ex  :
                                branch_zero_reg_ex;

    assign branch_taken_ex_comb =
        Unconditionbranch_ex | (Branch_ex && branch_zero_ex);

    // Compatibility/debug alias: this now represents the registered redirect
    // that actually controls the PC.
    wire PCSrc_id;
    assign PCSrc_id = branch_taken_mem;

    ALU ALU (
        .ALUop(ALUop_ex),
        .Readdata1(Readdata1_ex_mux),
        .Readdata2(Readdata2_ex_Src),
        .shamt(shamt_ex),
        .result(result_ex)
    );

    /*==============
         MEM stage
      ==============*/

    logic Memread_mem, Memwrite_mem;
    logic [63:0] result_mem;
    logic [63:0] Readdata2_mem_mux;
    wire [63:0] Readmemdata_mem;

    assign dmem_addr  = result_mem;
    assign dmem_wdata = Readdata2_mem_mux;
    assign dmem_we    = Memwrite_mem;
    assign dmem_re    = Memread_mem;

    assign Readmemdata_mem = dmem_rdata;

    wire mem_access;
    assign mem_access = Memread_mem | Memwrite_mem;
    assign mem_wait   = mem_access && !dmem_ready;

    /*==============
         WB stage
      ==============*/

    logic [63:0] Regwritedata_wb;
    logic        Regwritedata_zero_wb;

    /*==============
         Pipeline registers
      ==============*/

    // IF/ID: hold on memory/load-use stalls and flush on the registered branch
    // redirect from MEM.
    always @(posedge clk) begin
        if (rst) begin
            instruction_id <= 32'd0;
            pc_id           <= 64'd0;
        end
        else if (mem_wait) begin
            // hold
        end
        else if (branch_taken_mem) begin
            instruction_id <= 32'd0;
            pc_id           <= 64'd0;
        end
        else if (idhold_id) begin
            // hold
        end
        else if (imem_rsp_fire) begin
            instruction_id <= instruction_if;
            pc_id           <= imem_rsp_addr;
        end
        else begin
            instruction_id <= 32'd0;
            pc_id           <= 64'd0;
        end
    end

    // ID/EX: forwarding selects are pipeline metadata computed one stage early.
    always @(posedge clk) begin
        if (rst) begin
            Readdata1_ex         <= 64'd0;
            Readdata2_ex         <= 64'd0;
            Readdata2_zero_ex    <= 1'b1;
            Memread_ex           <= 1'b0;
            MemtoReg_ex          <= 1'b0;
            Memwrite_ex          <= 1'b0;
            ALUSrc_ex            <= 1'b0;
            Regwrite_ex          <= 1'b0;
            ALUop_ex             <= 4'd0;
            shamt_ex             <= 6'd0;
            Rm_ex                <= 5'd0;
            Rn_ex                <= 5'd0;
            Rd_ex                <= 5'd0;
            SE_Dtaddr_ex         <= 64'd0;
            Branch_ex            <= 1'b0;
            Unconditionbranch_ex <= 1'b0;
            branch_target_ex     <= 64'd0;
            fwdmuxa_ex           <= 2'b00;
            fwdmuxb_ex           <= 2'b00;
        end
        else if (mem_wait) begin
            // hold
        end
        else if (branch_taken_mem || idhold_id) begin
            Readdata1_ex         <= 64'd0;
            Readdata2_ex         <= 64'd0;
            Readdata2_zero_ex    <= 1'b1;
            Memread_ex           <= 1'b0;
            MemtoReg_ex          <= 1'b0;
            Memwrite_ex          <= 1'b0;
            ALUSrc_ex            <= 1'b0;
            Regwrite_ex          <= 1'b0;
            ALUop_ex             <= 4'd0;
            shamt_ex             <= 6'd0;
            Rm_ex                <= 5'd0;
            Rn_ex                <= 5'd0;
            Rd_ex                <= 5'd0;
            SE_Dtaddr_ex         <= 64'd0;
            Branch_ex            <= 1'b0;
            Unconditionbranch_ex <= 1'b0;
            branch_target_ex     <= 64'd0;
            fwdmuxa_ex           <= 2'b00;
            fwdmuxb_ex           <= 2'b00;
        end
        else begin
            Readdata1_ex         <= Readdata1_id;
            Readdata2_ex         <= Readdata2_id;
            Readdata2_zero_ex    <= Readdata2_zero_id;
            Memread_ex           <= Memread_id;
            MemtoReg_ex          <= MemtoReg_id;
            Memwrite_ex          <= Memwrite_id;
            ALUSrc_ex            <= ALUSrc_id;
            Regwrite_ex          <= Regwrite_id;
            ALUop_ex             <= ALUop_id;
            shamt_ex             <= shamt_id;
            Rm_ex                <= Rm_id;
            Rn_ex                <= Rn_id;
            Rd_ex                <= Rd_id;
            SE_Dtaddr_ex         <= SE_Dtaddr_id;
            Branch_ex            <= Branch_id;
            Unconditionbranch_ex <= Unconditionbranch_id;
            branch_target_ex     <= branch_target_id;
            fwdmuxa_ex           <= fwdmuxa_id;
            fwdmuxb_ex           <= fwdmuxb_id;
        end
    end

    // EX/MEM: capture the branch decision/target together.  When the previous
    // cycle's branch is taken, squash the younger EX instruction instead of
    // allowing it to enter MEM.
    always @(posedge clk) begin
        if (rst) begin
            Memread_mem      <= 1'b0;
            MemtoReg_mem     <= 1'b0;
            Memwrite_mem     <= 1'b0;
            Regwrite_mem     <= 1'b0;
            Rd_mem           <= 5'd0;
            result_mem       <= 64'd0;
            Readdata2_mem_mux<= 64'd0;
            branch_taken_mem <= 1'b0;
            branch_target_mem<= 64'd0;
        end
        else if (mem_wait) begin
            // hold
        end
        else if (branch_taken_mem) begin
            Memread_mem       <= 1'b0;
            MemtoReg_mem      <= 1'b0;
            Memwrite_mem      <= 1'b0;
            Regwrite_mem      <= 1'b0;
            Rd_mem            <= 5'd0;
            result_mem        <= 64'd0;
            Readdata2_mem_mux <= 64'd0;
            branch_taken_mem  <= 1'b0;
            branch_target_mem <= 64'd0;
        end
        else begin
            Memread_mem       <= Memread_ex;
            MemtoReg_mem      <= MemtoReg_ex;
            Memwrite_mem      <= Memwrite_ex;
            Regwrite_mem      <= Regwrite_ex;
            Rd_mem            <= Rd_ex;
            result_mem        <= result_ex;
            Readdata2_mem_mux <= Readdata2_ex_mux;
            branch_taken_mem  <= branch_taken_ex_comb;
            branch_target_mem <= branch_target_ex;
        end
    end

    // MEM/WB: select the data and its one-bit zero metadata on the D side of the
    // register.  This removes 64-bit zero reductions from WB -> CBZ and WB ->
    // register-file-metadata paths.
    always @(posedge clk) begin
        if (rst) begin
            Regwrite_wb            <= 1'b0;
            Rd_wb                  <= 5'd0;
            Regwritedata_wb        <= 64'd0;
            Regwritedata_zero_wb   <= 1'b1;
        end
        else if (mem_wait) begin
            Regwrite_wb            <= 1'b0;
            Rd_wb                  <= 5'd0;
            Regwritedata_wb        <= 64'd0;
            Regwritedata_zero_wb   <= 1'b1;
        end
        else begin
            Regwrite_wb          <= Regwrite_mem;
            Rd_wb                <= Rd_mem;
            Regwritedata_wb      <= MemtoReg_mem ? Readmemdata_mem : result_mem;
            Regwritedata_zero_wb <= MemtoReg_mem ? (~|Readmemdata_mem) : (~|result_mem);
        end
    end

    // Retain the legacy debug-visible hazard name without putting it on a
    // functional timing path.
    wire unused_hazardmux = hazardmux_id;

endmodule
