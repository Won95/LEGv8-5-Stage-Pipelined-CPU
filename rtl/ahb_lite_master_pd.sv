module ahb_lite_master_pd (
    input  wire        clk,
    input  wire        rst,

    input  wire        cpu_valid,
    input  wire        cpu_write,
    input  wire [63:0] cpu_addr,
    input  wire [63:0] cpu_wdata,
    output wire        cpu_ready,
    output wire [63:0] cpu_rdata,

    // AHB-Lite master signals
    output reg  [63:0] HADDR,
    output reg  [1:0]  HTRANS,
    output reg         HWRITE,
    output reg  [2:0]  HSIZE,
    output reg  [2:0]  HBURST,
    output reg  [3:0]  HPROT,
    output reg         HMASTLOCK,
    output reg  [63:0] HWDATA,
    input  wire [63:0] HRDATA,
    input  wire        HREADY,
    input  wire        HRESP
);

    localparam IDLE = 1'b0;
    localparam DATA = 1'b1;

    localparam [1:0] HTRANS_IDLE   = 2'b00;
    localparam [1:0] HTRANS_NONSEQ = 2'b10;

    reg        state;
    reg [63:0] wdata_q;

    // The core-side interface is blocking. Completion is returned only when
    // the AHB data phase finishes.
    assign cpu_ready = (state == DATA) && HREADY;
    assign cpu_rdata = HRDATA;

    always @(*) begin
        HADDR     = 64'd0;
        HTRANS    = HTRANS_IDLE;
        HWRITE    = 1'b0;
        HSIZE     = 3'b011;  // 8-byte transfer for the 64-bit data path
        HBURST    = 3'b000;  // SINGLE
        HPROT     = 4'b0011;
        HMASTLOCK = 1'b0;
        HWDATA    = wdata_q;

        if (state == IDLE && cpu_valid) begin
            // Address/control phase.
            HADDR  = cpu_addr;
            HTRANS = HTRANS_NONSEQ;
            HWRITE = cpu_write;
        end
        else if (state == DATA) begin
            // Data phase. This simple master does not issue a following transfer
            // in parallel, so the next address phase remains IDLE.
            HTRANS = HTRANS_IDLE;
            HWDATA = wdata_q;
        end
    end

    always @(posedge clk) begin
        if (rst) begin
            state   <= IDLE;
            wdata_q <= 64'd0;
        end
        else begin
            case (state)
                IDLE: begin
                    if (cpu_valid && HREADY) begin
                        state   <= DATA;
                        wdata_q <= cpu_wdata;
                    end
                end

                DATA: begin
                    if (HREADY)
                        state <= IDLE;
                end

                default: state <= IDLE;
            endcase
        end
    end

    // Error responses are not generated by the current fabric, but keep HRESP
    // on the interface so the bus remains AHB-Lite shaped.
    wire unused_hresp = HRESP;

endmodule
